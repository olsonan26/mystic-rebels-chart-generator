const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');

if (process.env.RUN_LIVE_CHAT_QA !== '1') throw new Error('Set RUN_LIVE_CHAT_QA=1 to permit one fictional paid model request through the locally configured service.');
fs.mkdirSync('tmp', { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8000');
  await page.getByRole('button', { name: 'Ask about your chart', exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0, 'initial sample should not interrupt');
  await page.getByLabel('Chart name', { exact: true }).fill('Fictional browser QA');
  await page.getByRole('button', { name: 'Generate chart', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('heading', { name: 'What do you want to know?', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Your question', { exact: true }).evaluate(e => e === document.activeElement), true);
  await page.getByLabel('Your question', { exact: true }).fill('What can I explore about my relationships, and what are the current sky positions?');
  const answerResponse = page.waitForResponse(r => r.url().endsWith('/api/chart-chat') && r.request().method() === 'POST', { timeout: 60000 });
  await dialog.getByRole('button', { name: 'Send question', exact: true }).click();
  const response = await answerResponse;
  const reply = await response.json();
  assert.equal(response.status(), 200, JSON.stringify(reply));
  assert.equal(reply.provider, 'OpenRouter');
  assert.equal(reply.model, 'deepseek/deepseek-v4.1-flash-1017');
  assert.equal(reply.personal_report_approved, false);
  await page.locator('.chart-chat-answer').waitFor();
  await dialog.getByText('Why this answer?', { exact: true }).click();
  await dialog.getByRole('heading', { name: 'Sky context', exact: true }).waitFor();
  assert.equal(await dialog.getByRole('columnheader', { name: 'Position', exact: true }).count(), 1);
  assert.equal(await dialog.locator('.chart-chat-stages li').count(), 7);
  await dialog.locator('select').selectOption('Venus');
  await page.screenshot({ path: 'tmp/chart-chat-desktop.png' });
  const downloaded = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download conversation', exact: true }).click();
  const download = await downloaded;
  await download.saveAs('tmp/chart-chat-browser-export.json');
  const packet = JSON.parse(fs.readFileSync('tmp/chart-chat-browser-export.json', 'utf8'));
  assert.equal(packet.exchanges.length, 1);
  assert.equal(packet.exchanges[0].reply.answer, reply.answer);
  assert.ok(packet.exchanges[0].reply.evidence.source_fingerprint);
  assert.equal(JSON.stringify(packet).includes('sk-or-'), false);
  // One real reply above. Deterministic follow-up checks the history contract,
  // safe error handling and browser persistence without another paid generation.
  await page.route('**/api/chart-chat', async route => {
    const data = route.request().postDataJSON();
    assert.deepEqual(data.history.map(t => t.role), ['user', 'assistant']);
    assert.equal(data.history[0].content, packet.exchanges[0].question);
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'QA service unavailable. Your question is kept.' } }) });
  });
  await page.getByLabel('Your question', { exact: true }).fill('How can I apply that?');
  await dialog.getByRole('button', { name: 'Send question', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(await page.getByLabel('Your question', { exact: true }).inputValue(), 'How can I apply that?');
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Ask about your chart', exact: true }).evaluate(e => e === document.activeElement), true);
  await page.reload();
  await page.getByRole('button', { name: 'Ask about your chart', exact: true }).waitFor();
  await page.getByLabel('Chart name', { exact: true }).fill('Fictional browser QA');
  await page.getByRole('button', { name: 'Generate chart', exact: true }).click();
  await page.locator('.chart-chat-answer').waitFor();
  assert.equal(await page.locator('.chart-chat-exchange').count(), 1);
  assert.equal(await page.getByLabel('Your question', { exact: true }).inputValue(), 'How can I apply that?');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'tmp/chart-chat-mobile.png' });
  const bounds = await dialog.boundingBox();
  assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height <= 844);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await dialog.getByRole('button', { name: 'Close chart chat', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByLabel('Chart name', { exact: true }).fill('Different fictional person');
  await page.getByRole('button', { name: 'Generate chart', exact: true }).click();
  await dialog.getByRole('heading', { name: 'What do you want to know?', exact: true }).waitFor();
  assert.equal(await page.locator('.chart-chat-exchange').count(), 0);
  assert.equal(await page.getByLabel('Your question', { exact: true }).inputValue(), '');
  assert.deepEqual(errors, []);
  fs.writeFileSync('tmp/chart-chat-browser-receipt.json', JSON.stringify({ verified_at: new Date().toISOString(), real_provider_reply: true, provider: reply.provider, model: reply.model, source_count: reply.evidence.sources.length, stages: 7, automatic_popup: true, keyboard: true, export_exact: true, followup_history_mocked: true, error_draft_preserved: true, reload_restore: true, different_chart_isolation: true, mobile_bounds_and_overflow: true, page_errors: errors }, null, 2));
  console.log(fs.readFileSync('tmp/chart-chat-browser-receipt.json', 'utf8'));
  await browser.close();
})().catch(async e => { console.error(e); if (browser) await browser.close(); process.exit(1); });
